// 辞書の見出し語と判定対象の文字列で同じ畳み込みをするための関数。
// NFKC 正規化（全角スペースの区切りは残す）のあと、異体字（髙→高 など）を代表字に寄せる。
// 辞書のデータは畳み込み済みで保存してあるので、照合する側も同じ fold() を通すこと。
// ============================================================================

/** 異体字 → 代表字の対応表（施設データの検証で使った表と同じ） */
const VARIANTS = {
  髙: '高', 﨑: '崎', 德: '徳', 濵: '浜', 濱: '浜', 邊: '辺', 邉: '辺', 國: '国', 澤: '沢',
  惠: '恵', 齋: '斎', 齊: '斉', 嶋: '島', 會: '会', 眞: '真', 冨: '富', 栁: '柳', 﨏: '迫',
  渕: '淵', 廣: '広', 榮: '栄', 圓: '円', 舩: '船', 櫻: '桜', 淺: '浅', 實: '実', 鷗: '鴎',
  藏: '蔵', 彌: '弥', 瀧: '滝', 瀨: '瀬', 龍: '竜', 關: '関', 嵜: '崎',
};

/**
 * 文字列を辞書照合用に畳み込む（NFKC → 異体字を代表字へ）。
 * @param {string} s 畳み込み前の文字列
 * @returns {string} 畳み込み後の文字列
 */
export function fold(s) {
  // NFKC は全角スペース（U+3000）を半角に変えてしまい、姓と名の区切りが壊れる。区切りで分けて畳み込み、区切りは残す
  return String(s)
    .split('\u3000')
    .map((part) => [...part.normalize('NFKC')].map((c) => VARIANTS[c] ?? c).join(''))
    .join('\u3000');
}
